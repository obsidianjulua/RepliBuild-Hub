#!/usr/bin/env julia
# Regenerate the sample assets in this directory. They are committed, so this
# only needs running after changing it.
#
#   julia --project=examples/ObjectSim examples/ObjectSim/assets/make_assets.jl
#
#   rock.obj  — a lumpy low-poly stone (a moving object: used as a convex hull)
#   bowl.obj  — a basin, open on top (static scenery: a concave triangle mesh)
#   ramp.stl  — a wedge, binary STL (static scenery)
#   ramp.obj is hand-written (quads, to exercise polygon triangulation).

using ObjectSim
using ObjectSim: TriMesh, Vec3, v3, vunit, vscale, vadd, vsub, vcross

const DIR = @__DIR__

# Icosahedron, subdivided once and pushed onto an ellipsoid with a little
# deterministic wobble: 42 vertices, nearly convex, so the hull bullet3 builds
# from it looks like the mesh that is drawn.
function rock()
    t = (1 + sqrt(5)) / 2
    verts = [vunit(v3(x...)) for x in ((-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0),
                                       (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t),
                                       (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1))]
    faces = [(1, 12, 6), (1, 6, 2), (1, 2, 8), (1, 8, 11), (1, 11, 12), (2, 6, 10), (6, 12, 5),
             (12, 11, 3), (11, 8, 7), (8, 2, 9), (4, 10, 5), (4, 5, 3), (4, 3, 7), (4, 7, 9),
             (4, 9, 10), (5, 10, 6), (3, 5, 12), (7, 3, 11), (9, 7, 8), (10, 9, 2)]
    mid = Dict{Tuple{Int,Int},Int}()
    function midpoint(a, b)
        get!(mid, minmax(a, b)) do
            push!(verts, vunit(vscale(vadd(verts[a], verts[b]), 0.5f0))); length(verts)
        end
    end
    sub = NTuple{3,Int32}[]
    for (a, b, c) in faces
        ab, bc, ca = midpoint(a, b), midpoint(b, c), midpoint(c, a)
        append!(sub, Int32.(f) for f in ((a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)))
    end
    wobble(v) = 1 + 0.06f0 * sin(5v[1] + 2v[2]) * cos(3v[3] - v[1])
    shaped = [vscale((v[1] * 0.6f0, v[2] * 0.42f0, v[3] * 0.5f0), wobble(v)) for v in verts]
    return TriMesh(shaped, sub)
end

# A square grid whose height rises with the distance from the centre:
# y = depth · (r / radius)² inside the radius, flat outside. Open surface.
function bowl(; half = 4.0, n = 28, radius = 3.6, depth = 1.6)
    verts = Vec3[]; faces = NTuple{3,Int32}[]
    for j in 0:n, i in 0:n
        x = -half + 2half * i / n; z = -half + 2half * j / n
        r = min(hypot(x, z), radius)
        push!(verts, v3(x, depth * (r / radius)^2, z))
    end
    id(i, j) = Int32(j * (n + 1) + i + 1)
    for j in 0:n - 1, i in 0:n - 1
        a, b, c, d = id(i, j), id(i + 1, j), id(i, j + 1), id(i + 1, j + 1)
        push!(faces, (a, c, b), (b, c, d))           # facing +Y
    end
    return TriMesh(verts, faces)
end

function save_stl(path, m::TriMesh)
    open(path, "w") do io
        write(io, rpad("ObjectSim sample ramp", 80))
        write(io, htol(UInt32(length(m.faces))))
        for (a, b, c) in m.faces
            p, q, r = m.vertices[a], m.vertices[b], m.vertices[c]
            foreach(x -> write(io, htol(Float32(x))), vunit(vcross(vsub(q, p), vsub(r, p))))
            foreach(v -> foreach(x -> write(io, htol(Float32(x))), v), (p, q, r))
            write(io, UInt16(0))
        end
    end
end

save_obj(joinpath(DIR, "rock.obj"), rock(); comment = "ObjectSim sample: lumpy stone, ~1.2 x 0.85 x 1.0 m\ngenerated by make_assets.jl")
save_obj(joinpath(DIR, "bowl.obj"), bowl(); comment = "ObjectSim sample: basin 8 x 8 m, 1.6 m deep\ngenerated by make_assets.jl")
save_stl(joinpath(DIR, "ramp.stl"), load_mesh(joinpath(DIR, "ramp.obj")))
println("wrote rock.obj, bowl.obj, ramp.stl in $DIR")
