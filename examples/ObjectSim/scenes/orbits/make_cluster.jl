#!/usr/bin/env julia
# Regenerate cluster.toml: 40 bodies of random mass scattered in a ball,
# moving about as fast as a cluster that holds itself up (random motions near
# virial balance) plus a slow overall spin, in N-body units (G = 1). Close
# encounters fling some out, a few collide and merge. Fixed seed, so the file
# is the same every time.
#
#   julia examples/ObjectSim/scenes/orbits/make_cluster.jl
using Random
rng = Random.Xoshiro(20261115)
N = 40
io = IOBuffer()
println(io, """# Forty bodies collapsing under their own gravity (N-body units, G = 1).
# Bodies that touch merge, conserving mass and momentum; watch the count drop.
# Generated by make_cluster.jl — edit that, not this.

[system]
units = "nbody"
softening = 0.0

[view]
days_per_second = 0.6
exaggerate = 1
scale = 3
""")
palette = ("#d94f3d", "#3d8bd9", "#e8b33a", "#4fb06a", "#9a6fd6", "#e07b39", "#38b2ac", "#c95f9b")
for k in 1:N
    # uniform in a ball of radius 2
    p = (0.0, 0.0, 0.0)
    while true
        p = Tuple(4 .* rand(rng, 3) .- 2)
        sum(abs2, p) <= 4 && break
    end
    m = 0.02 + 0.08 * rand(rng)
    r = 0.025 * cbrt(m / 0.05)
    spin = 0.12 .* (-p[2], p[1], 0.0)                       # slow rotation about z
    # total mass ≈ 2.4 in a ball of radius 2: virial speed √(0.3·G·M/R)·… ≈ 0.5 per axis
    v = spin .+ 0.42 .* (randn(rng), randn(rng), randn(rng))
    f(x) = round(x; digits = 5)
    println(io, """
[[body]]
name = "b$k"
mass = $(f(m))
radius = $(f(r))
color = "$(palette[mod1(k, length(palette))])"
position = [$(f(p[1])), $(f(p[2])), $(f(p[3]))]
velocity = [$(f(v[1])), $(f(v[2])), $(f(v[3]))]""")
end
write(joinpath(@__DIR__, "cluster.toml"), String(take!(io)))
println("wrote cluster.toml")
