#!/bin/bash
#
# Harvest MicroPython's embed package into packages/micropython/embed/.
#
# WHY THIS EXISTS
# ---------------
# MicroPython cannot be compiled from a bare checkout under one flag set: its
# build runs Python scripts that preprocess every source, scan for MP_QSTR_*
# names, module registrations and root pointers, and generate genhdr/
# (qstrdefs.generated.h, moduledefs.h, root_pointers.h, mpversion.h). That is a
# build-time generator, which RepliBuild does not run.
#
# Upstream provides the escape hatch itself: ports/embed. Its embed.mk runs
# those generators once against a project's mpconfigport.h and writes a
# self-contained tree (py/*.c, the generated genhdr/, the port glue) meant to
# be "compiled by any build system". This script runs it against the Hub's
# committed mpconfigport.h and puts the result in embed/, which replibuild.toml
# compiles as a local dependency. Same arrangement as llamacpp/vulkan and
# onednn/ocl: upstream's generator, run here, output gitignored (3 MB).
#
# Re-run whenever TAG moves or mpconfigport.h changes. genhdr is a function of
# BOTH: the qstr table is scanned under that exact config.
#
#   ./harvest_embed.sh
#
# Needs: git, make, python3, a C compiler (the scan preprocesses each source).

set -euo pipefail

TAG="v1.29.0"
COMMIT="0fd6c573ea815774668bbb16b8e197c8822368b2"
URL="https://github.com/micropython/micropython.git"

PKG="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG="${PKG}/mpconfigport.h"
OUT="${PKG}/embed"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

for tool in git make python3 cc; do
    command -v "$tool" >/dev/null || { echo "ERROR: $tool not found in PATH"; exit 1; }
done
[ -f "$CONFIG" ] || { echo "ERROR: $CONFIG missing"; exit 1; }

# ── 1. Pinned clone, and prove it is the pin ─────────────────────────────────
git clone -q -c advice.detachedHead=false --depth 1 --branch "$TAG" "$URL" "$WORK/micropython"
HEAD="$(git -C "$WORK/micropython" rev-parse HEAD)"
if [ "$HEAD" != "$COMMIT" ]; then
    echo "ERROR: $TAG resolved to $HEAD, expected $COMMIT (tag moved?)"
    exit 1
fi

# ── 2. Run upstream's embed.mk against the Hub config ────────────────────────
mkdir -p "$WORK/project"
cp "$CONFIG" "$WORK/project/mpconfigport.h"
cat > "$WORK/project/micropython_embed.mk" <<EOF
MICROPYTHON_TOP = $WORK/micropython
include \$(MICROPYTHON_TOP)/ports/embed/embed.mk
EOF
make -s -C "$WORK/project" -f micropython_embed.mk

# ── 3. Replace embed/ and record what produced it ────────────────────────────
rm -rf "$OUT"
cp -r "$WORK/project/micropython_embed" "$OUT"

CONFIG_SHA="$(sha256sum "$CONFIG" | cut -d' ' -f1)"
cat > "$OUT/HARVEST.md" <<EOF
# MicroPython embed harvest

Generated by \`harvest_embed.sh\`. Do not edit; re-run the script.

- upstream: $URL
- tag: $TAG
- commit: $HEAD
- config: mpconfigport.h
- config_sha256: $CONFIG_SHA
- python: $(python3 --version 2>&1)
- make: $(make --version | head -1)
- cc: $(cc --version | head -1)
EOF

echo "embed/ harvested from $TAG ($HEAD), config sha256 $CONFIG_SHA"
